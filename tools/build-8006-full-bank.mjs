// tools/build-8006-full-bank.mjs — generate site/questions-8006-full.js from the
// production inventory (200 items: 173 single-select + 27 multiple-select).
//
// Source of truth is content-infra/production-inventory. This script is a pure
// transform: id / domain / stem / options / answer indices / explanation.
// It never edits question content. Re-run after any re-delivery:
//   node tools/build-8006-full-bank.mjs
//
// Output shape mirrors the 5001 bank (window.DM_BANK) so the quiz UI stays
// familiar: { id, code, subtest, q, options[], answer, multi?, answers?, explain, dex{} }.
//   - single-select items: answer = index (number)
//   - multiple-select items: multi = true, answers = [indices], answer = first index
// The bank is a JS file (not JSON) so it can be served as a static asset
// without a fetch round-trip, same convention as site/questions.js.

import { readFileSync, writeFileSync } from 'node:fs';

const SOURCES = [
  { path: 'content-infra/production-inventory/8006-single.json' },
  { path: 'content-infra/production-inventory/8006-multiselect-normalized.json' },
];
const OUT = 'site/questions-8006-full.js';

const DOMAIN_ORDER = [
  'Foundational Literacy Skills',
  'Fluency and Vocabulary',
  'Comprehension and Written Expression',
];

let bank = [];
const dist = {};
let multiCount = 0;

for (const src of SOURCES) {
  const raw = JSON.parse(readFileSync(src.path, 'utf8'));
  const items = raw.items || raw;
  if (!Array.isArray(items)) throw new Error('no items array in ' + src.path);
  for (const it of items) {
    // batch1 走的是 human-reviewed；production-inventory 的单选批来自
    // item-session-2026-08-30 生产流程、状态字段停在 draft（用户已确认直接挂线）。
    const st = it.review_status || '';
    if (st !== 'human-reviewed' && st !== 'draft') {
      throw new Error(`item ${it.id}: unexpected review_status=${st}`);
    }
    const texts = it.choices.map((c) => (typeof c === 'string' ? c : c.text));
    let answersRaw = it.correct_answer;
    if (!Array.isArray(answersRaw)) answersRaw = [answersRaw];
    const idxs = answersRaw.map((a) => texts.indexOf(a));
    if (idxs.some((i) => i < 0)) throw new Error(`item ${it.id}: correct_answer not among choices`);
    const stem = it.stem || '';
    const stim = it.stimulus || '';
    const q = stim ? `${stim}\n\n${stem}` : stem;
    const dex = {};
    for (const [k, v] of Object.entries(it.distractor_explanations || {})) dex[k] = v;
    const item = {
      id: it.id,
      code: String(it.test_code || '8006'),
      subtest: it.content_domain,
      q,
      options: texts,
      answer: idxs[0],
      explain: it.explanation || '',
      dex,
    };
    if (idxs.length > 1) {
      item.multi = true;
      item.answers = idxs;
      multiCount++;
    }
    bank.push(item);
    dist[it.content_domain] = (dist[it.content_domain] || 0) + 1;
  }
}

// stable ordering: domain order, then id
bank.sort((a, b) => {
  const da = DOMAIN_ORDER.indexOf(a.subtest);
  const db = DOMAIN_ORDER.indexOf(b.subtest);
  if (da !== db) return da - db;
  return a.id < b.id ? -1 : 1;
});

const ids = new Set(bank.map((b) => b.id));
if (ids.size !== bank.length) throw new Error('duplicate ids in bank');

const header = `// GENERATED by tools/build-8006-full-bank.mjs — do not edit by hand.
// Source: content-infra/production-inventory/8006-single.json + 8006-multiselect-normalized.json (human-reviewed)
// ${bank.length} items · ${dist['Foundational Literacy Skills'] || 0} Foundational Literacy Skills | ${dist['Fluency and Vocabulary'] || 0} Fluency and Vocabulary | ${dist['Comprehension and Written Expression'] || 0} Comprehension and Written Expression · ${multiCount} multiple-select
// Learndiag original items — not official ETS content.
`;

writeFileSync(OUT, header + 'window.DM_BANK_8006_FULL = ' + JSON.stringify(bank) + ';\n', 'utf8');
console.log(`wrote ${OUT}: ${bank.length} items (${multiCount} multi-select), dist=${JSON.stringify(dist)}`);
