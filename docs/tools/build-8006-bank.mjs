// tools/build-8006-bank.mjs — generate site/questions-8006.js from the signed
// 8006 batch (content-infra/items/8006-batch1.json, human-reviewed 2026-09-03).
//
// Source of truth is content-infra (D5 acceptance pipeline output). This script
// is a pure transform: id / domain / stem / options / answer index / explanation.
// It never edits question content. Re-run after any re-delivery of the batch:
//   node tools/build-8006-bank.mjs
//
// Output shape mirrors the 5001 bank (window.DM_BANK) so the quiz UI stays
// familiar: { id, code, subtest, q, options[], answer, explain, dex{} }.
// The bank is a JS file (not JSON) so it can be served as a static asset
// without a fetch round-trip, same convention as site/questions.js.

import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'content-infra/items/8006-batch1.json';
const OUT = 'site/questions-8006.js';

const raw = JSON.parse(readFileSync(SRC, 'utf8'));
const items = raw.items || raw;
if (!Array.isArray(items) || items.length === 0) {
  console.error('no items found in ' + SRC);
  process.exit(1);
}

const DOMAIN_ORDER = [
  'Foundational Literacy Skills',
  'Fluency and Vocabulary',
  'Comprehension and Written Expression',
];

const bank = items.map((it) => {
  const texts = it.choices.map((c) => (typeof c === 'string' ? c : c.text));
  let answer = it.correct_answer;
  if (Array.isArray(answer)) {
    if (answer.length !== 1) {
      // mini test ships single-select only; multiselects live in the
      // production inventory, not in batch1. Fail loudly if that changes.
      throw new Error(`item ${it.id}: unexpected multiple answers ${JSON.stringify(answer)}`);
    }
    answer = answer[0];
  }
  const aIdx = texts.indexOf(answer);
  if (aIdx < 0) throw new Error(`item ${it.id}: correct_answer not among choices`);
  const dex = {};
  for (const [k, v] of Object.entries(it.distractor_explanations || {})) dex[k] = v;
  return {
    id: it.id,
    code: String(it.test_code || '8006'),
    subtest: it.content_domain,
    q: it.stem,
    options: texts,
    answer: aIdx,
    explain: it.explanation || '',
    dex,
  };
});

// sanity: domain distribution must stay 12/9/9
const dist = {};
for (const q of bank) dist[q.subtest] = (dist[q.subtest] || 0) + 1;
const sig = DOMAIN_ORDER.map((d) => `${d}:${dist[d] || 0}`).join(' | ');
if (dist[DOMAIN_ORDER[0]] !== 12 || dist[DOMAIN_ORDER[1]] !== 9 || dist[DOMAIN_ORDER[2]] !== 9) {
  console.error('domain distribution changed — update the page copy and spec before shipping: ' + sig);
  process.exit(1);
}

// order the bank by domain (official order), shuffled inside each domain at
// runtime by the quiz — keeps a stable, reviewable file
bank.sort((a, b) => DOMAIN_ORDER.indexOf(a.subtest) - DOMAIN_ORDER.indexOf(b.subtest));

const header = `// GENERATED by tools/build-8006-bank.mjs — do not edit by hand.
// Source: ${SRC} (human-reviewed 2026-09-03, see content-infra/items/8006-batch1-answer-review.md)
// ${bank.length} items · ${sig}
// Learndiag original items — not official ETS content.
window.DM_BANK_8006 = ${JSON.stringify(bank)};
`;
writeFileSync(OUT, header, 'utf8');
console.log(`wrote ${OUT}: ${bank.length} items (${sig})`);
